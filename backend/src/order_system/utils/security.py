"""Password hashing and HS256 JWTs (standard library only).

Used by the Auth Lambda (hash + sign) and the Lambda Authorizer (verify).
The signing key is ``JWT_SECRET``, generated by Terraform and given only to
those two functions.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import json
import secrets
import time
from typing import Any

PBKDF2_ITERATIONS = 210_000
_ALG = "pbkdf2_sha256"


def hash_password(password: str, *, iterations: int = PBKDF2_ITERATIONS) -> str:
    """Return ``pbkdf2_sha256$<iterations>$<salt>$<hash>``; the iteration
    count is stored so it can be raised later without breaking old hashes."""
    salt = secrets.token_hex(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode(), salt.encode(), iterations).hex()
    return f"{_ALG}${iterations}${salt}${digest}"


def verify_password(password: str, stored: str) -> bool:
    try:
        alg, iterations, salt, digest = stored.split("$")
        if alg != _ALG:
            return False
        candidate = hashlib.pbkdf2_hmac("sha256", password.encode(), salt.encode(), int(iterations)).hex()
    except (ValueError, AttributeError):
        return False
    return hmac.compare_digest(candidate, digest)


def _b64(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).decode().rstrip("=")


def _unb64(text: str) -> bytes:
    return base64.urlsafe_b64decode(text + "=" * (-len(text) % 4))


def sign_jwt(claims: dict[str, Any], secret: str) -> str:
    header = _b64(json.dumps({"alg": "HS256", "typ": "JWT"}, separators=(",", ":")).encode())
    payload = _b64(json.dumps(claims, separators=(",", ":")).encode())
    sig = hmac.new(secret.encode(), f"{header}.{payload}".encode(), hashlib.sha256).digest()
    return f"{header}.{payload}.{_b64(sig)}"


def verify_jwt(token: str, secret: str, *, issuer: str, token_use: str) -> dict[str, Any] | None:
    """Signature, algorithm, issuer, token type and expiry. ``None`` when any
    check fails; callers never learn which one."""
    if not secret or not token:
        return None
    try:
        header_b64, payload_b64, sig_b64 = token.split(".")
        header = json.loads(_unb64(header_b64))
        if header.get("alg") != "HS256":  # rejects "none" and algorithm confusion
            return None
        expected = hmac.new(secret.encode(), f"{header_b64}.{payload_b64}".encode(), hashlib.sha256).digest()
        if not hmac.compare_digest(_b64(expected), sig_b64):
            return None
        claims = json.loads(_unb64(payload_b64))
    except (ValueError, TypeError, json.JSONDecodeError):
        return None
    if not isinstance(claims, dict):
        return None
    if claims.get("iss") != issuer or claims.get("token_use") != token_use or not claims.get("sub"):
        return None
    if int(claims.get("exp", 0)) <= time.time():
        return None
    return claims
